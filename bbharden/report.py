"""Reporters: console, markdown, SARIF 2.1.0, JSON."""

from __future__ import annotations

import html
import json
import re
from typing import List

from . import __version__, compliance
from .findings import Finding, Severity
from .suppress import fingerprint

REPO_URL = "https://github.com/8l4ck8y73-afk/bbharden"

# Everything in a finding can originate from the scanned repository (file names,
# the offending line, a workflow ref). Reports are read in terminals, PR comments
# and the GitHub UI, so untrusted text is neutralised first.
_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f-\x9f\u202a-\u202e\u2066-\u2069]")


def _clean(s) -> str:
    """Strip terminal escapes / control and bidi-override characters."""
    return _CTRL.sub("?", str(s))


def _md(s) -> str:
    """Make untrusted text inert in Markdown/HTML (tables, tags, links)."""
    s = html.escape(_clean(s), quote=False)
    return s.replace("|", "\\|").replace("\n", " ")

_SEV_EMOJI = {
    Severity.CRITICAL: "🟥",
    Severity.HIGH: "🟧",
    Severity.MEDIUM: "🟨",
    Severity.LOW: "🟦",
    Severity.INFO: "⬜",
}


def _sorted(findings: List[Finding]) -> List[Finding]:
    return sorted(findings, key=lambda f: (-f.severity.rank, f.file, f.line))


def summary_counts(findings: List[Finding]) -> dict:
    counts = {s: 0 for s in Severity}
    for f in findings:
        counts[f.severity] += 1
    return counts


def console(findings: List[Finding], root: str) -> str:
    out = []
    counts = summary_counts(findings)
    out.append(f"BlackByte Hardener v{__version__} — scanned {_clean(root)}")
    out.append("")
    if not findings:
        out.append("✓ No findings. Clean scan.")
        return "\n".join(out)
    for f in _sorted(findings):
        em = _SEV_EMOJI[f.severity]
        fix = "  [autofix available]" if f.has_autofix else ""
        out.append(f"{em} {f.severity.value.upper():<8} {f.rule_id}{fix}")
        out.append(f"   {_clean(f.title)}")
        out.append(f"   {_clean(f.file)}:{f.line}")
        if f.evidence:
            out.append(f"   evidence: {_clean(f.evidence)}")
        out.append(f"   → {_clean(f.message)}")
        out.append("")
    line = "  ".join(
        f"{_SEV_EMOJI[s]} {counts[s]} {s.value}"
        for s in Severity if counts[s]
    )
    out.append(f"Summary: {line}")
    return "\n".join(out)


def markdown(findings: List[Finding], root: str) -> str:
    counts = summary_counts(findings)
    out = [f"## 🛡️ BlackByte Hardener report", ""]
    out.append(
        "| Severity | Count |\n|---|---|\n" +
        "\n".join(
            f"| {_SEV_EMOJI[s]} {s.value} | {counts[s]} |"
            for s in Severity if counts[s]
        )
    )
    out.append("")
    if not findings:
        out.append("✅ **No findings.** Clean scan.")
        return "\n".join(out)
    out.append("| Sev | Rule | Location | Finding | Autofix |")
    out.append("|---|---|---|---|---|")
    for f in _sorted(findings):
        fix = "✅" if f.has_autofix else ""
        out.append(
            f"| {_SEV_EMOJI[f.severity]} | `{f.rule_id}` | "
            f"{_md(f.file)}:{f.line} | {_md(f.title)} | {fix} |"
        )
    out.append("")
    out.append("<details><summary>Remediation details</summary>\n")
    for f in _sorted(findings):
        out.append(f"### `{f.rule_id}` — {_md(f.title)}")
        out.append(f"**{_md(f.file)}:{f.line}** · {f.severity.value}"
                   + (f" · {f.cwe}" if f.cwe else ""))
        out.append(f"\n{_md(f.message)}\n")
        out.append(f"**Fix:** {_md(f.remediation)}\n")
    out.append("</details>")
    out.append(f"\n_Generated by BlackByte Hardener v{__version__}._")
    return "\n".join(out)


def sarif(findings: List[Finding], root: str) -> str:
    rules = {}
    results = []
    for f in findings:
        if f.rule_id not in rules:
            rules[f.rule_id] = {
                "id": f.rule_id,
                "name": f.rule_id,
                "shortDescription": {"text": f.title},
                "fullDescription": {"text": f.remediation},
                "defaultConfiguration": {"level": f.severity.sarif_level},
                "help": {"text": f.remediation},
                "properties": {
                    "security-severity": _security_severity(f.severity),
                    # GitHub surfaces CWE links from `external/cwe/...` tags.
                    "tags": ["security"] + (
                        [f"external/cwe/{f.cwe.lower()}"] if f.cwe else [])
                    + compliance.references(f.rule_id),
                },
            }
        results.append({
            "ruleId": f.rule_id,
            "level": f.severity.sarif_level,
            "message": {"text": _clean(f.message) + " " + _clean(f.remediation)},
            "locations": [{
                "physicalLocation": {
                    "artifactLocation": {"uri": _clean(f.file).replace("\\", "/")},
                    "region": {"startLine": max(f.line, 1)},
                }
            }],
            # Stable across line shifts, so GitHub tracks an alert instead of
            # closing and re-opening it whenever code above it moves.
            "partialFingerprints": {"bbharden/v1": fingerprint(f)},
        })
    doc = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {
                "name": "BlackByte Hardener",
                "informationUri": REPO_URL,
                "version": __version__,
                "rules": list(rules.values()),
            }},
            "results": results,
        }],
    }
    return json.dumps(doc, indent=2)


def as_json(findings: List[Finding], root: str) -> str:
    counts = summary_counts(findings)
    return json.dumps({
        "tool": "bbharden",
        "version": __version__,
        "root": root,
        "summary": {s.value: counts[s] for s in Severity},
        "findings": [dict(f.to_dict(), references=compliance.references(f.rule_id))
                     for f in _sorted(findings)],
        "references_note": compliance.DISCLAIMER,
    }, indent=2)


def _security_severity(sev: Severity) -> str:
    # GitHub code scanning maps this 0-10 number to its own levels.
    return {
        Severity.CRITICAL: "9.5",
        Severity.HIGH: "8.0",
        Severity.MEDIUM: "5.5",
        Severity.LOW: "3.0",
        Severity.INFO: "1.0",
    }[sev]


