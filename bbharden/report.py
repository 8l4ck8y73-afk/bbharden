"""Reporters: console, markdown, SARIF 2.1.0, JSON."""

from __future__ import annotations

import json
from typing import List

from . import __version__
from .findings import Finding, Severity

_SEV_EMOJI = {
    Severity.CRITICAL: "🟥",
    Severity.HIGH: "🟧",
    Severity.MEDIUM: "🟨",
    Severity.LOW: "🟦",
    Severity.INFO: "⬜",
}


def _sorted(findings: List[Finding]) -> List[Finding]:
    return sorted(findings, key=lambda f: (-f.severity.rank, f.file, f.line))


def summary_counts(findings: List[Finding]) -> dict:
    counts = {s: 0 for s in Severity}
    for f in findings:
        counts[f.severity] += 1
    return counts


def console(findings: List[Finding], root: str) -> str:
    out = []
    counts = summary_counts(findings)
    out.append(f"BlackByte Hardener v{__version__} — scanned {root}")
    out.append("")
    if not findings:
        out.append("✓ No findings. Clean scan.")
        return "\n".join(out)
    for f in _sorted(findings):
        em = _SEV_EMOJI[f.severity]
        fix = "  [autofix available]" if f.has_autofix else ""
        out.append(f"{em} {f.severity.value.upper():<8} {f.rule_id}{fix}")
        out.append(f"   {f.title}")
        out.append(f"   {f.file}:{f.line}")
        if f.evidence:
            out.append(f"   evidence: {f.evidence}")
        out.append(f"   → {f.message}")
        out.append("")
    line = "  ".join(
        f"{_SEV_EMOJI[s]} {counts[s]} {s.value}"
        for s in Severity if counts[s]
    )
    out.append(f"Summary: {line}")
    return "\n".join(out)


def markdown(findings: List[Finding], root: str) -> str:
    counts = summary_counts(findings)
    out = [f"## 🛡️ BlackByte Hardener report", ""]
    out.append(
        "| Severity | Count |\n|---|---|\n" +
        "\n".join(
            f"| {_SEV_EMOJI[s]} {s.value} | {counts[s]} |"
            for s in Severity if counts[s]
        )
    )
    out.append("")
    if not findings:
        out.append("✅ **No findings.** Clean scan.")
        return "\n".join(out)
    out.append("| Sev | Rule | Location | Finding | Autofix |")
    out.append("|---|---|---|---|---|")
    for f in _sorted(findings):
        fix = "✅" if f.has_autofix else ""
        title = f.title.replace("|", "\\|")
        out.append(
            f"| {_SEV_EMOJI[f.severity]} | `{f.rule_id}` | "
            f"`{f.file}:{f.line}` | {title} | {fix} |"
        )
    out.append("")
    out.append("<details><summary>Remediation details</summary>\n")
    for f in _sorted(findings):
        out.append(f"### `{f.rule_id}` — {f.title}")
        out.append(f"**{f.file}:{f.line}** · {f.severity.value}"
                   + (f" · {f.cwe}" if f.cwe else ""))
        out.append(f"\n{f.message}\n")
        out.append(f"**Fix:** {f.remediation}\n")
    out.append("</details>")
    out.append(f"\n_Generated by BlackByte Hardener v{__version__}._")
    return "\n".join(out)


def sarif(findings: List[Finding], root: str) -> str:
    rules = {}
    results = []
    for f in findings:
        if f.rule_id not in rules:
            rules[f.rule_id] = {
                "id": f.rule_id,
                "name": f.rule_id,
                "shortDescription": {"text": f.title},
                "fullDescription": {"text": f.remediation},
                "defaultConfiguration": {"level": f.severity.sarif_level},
                "properties": {
                    "security-severity": _security_severity(f.severity),
                    **({"cwe": f.cwe} if f.cwe else {}),
                },
            }
        results.append({
            "ruleId": f.rule_id,
            "level": f.severity.sarif_level,
            "message": {"text": f.message + " " + f.remediation},
            "locations": [{
                "physicalLocation": {
                    "artifactLocation": {"uri": f.file},
                    "region": {"startLine": max(f.line, 1)},
                }
            }],
        })
    doc = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {
                "name": "BlackByte Hardener",
                "informationUri": "https://github.com/8L4CK8Y73/bbharden",
                "version": __version__,
                "rules": list(rules.values()),
            }},
            "results": results,
        }],
    }
    return json.dumps(doc, indent=2)


def as_json(findings: List[Finding], root: str) -> str:
    counts = summary_counts(findings)
    return json.dumps({
        "tool": "bbharden",
        "version": __version__,
        "root": root,
        "summary": {s.value: counts[s] for s in Severity},
        "findings": [f.to_dict() for f in _sorted(findings)],
    }, indent=2)


def _security_severity(sev: Severity) -> str:
    # GitHub code scanning maps this 0-10 number to its own levels.
    return {
        Severity.CRITICAL: "9.5",
        Severity.HIGH: "8.0",
        Severity.MEDIUM: "5.5",
        Severity.LOW: "3.0",
        Severity.INFO: "1.0",
    }[sev]
